#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
实验 3：机器人评测为什么这么难 —— 四个可以算的量

机器人论文里最常见的数字是「成功率从 62% 提升到 71%」。这个数字通常
不可信，原因不是造假，是**样本量根本不够**。本实验算四个量：

  1. 置信区间有多宽
     n 次试验的成功率，95% 置信区间是多少？n=20 时是 ±15 个百分点。

  2. 要多少次试验才能分出高下
     两比例检验的样本量公式。区分 70% vs 80%，每组要 290 次。

  3. 成功率是对测试分布求平均 —— 换个分布，排名会翻转
     用实验 1 里两条真实的曲线（BC / DAgger），在三种测试分布下平均。

  4. 评测集泄漏
     训练场景和评测场景重叠 20%，报告的成功率会虚高多少？

运行：python examples/05_learning_from_data/03_evaluation_power.py
依赖：无（只用标准库）
"""

import math


# ---------------------------------------------------------------- 输出对齐

def width(s):
    return sum(2 if ord(c) > 0x2E80 else 1 for c in s)


def pad(s, n):
    return s + " " * max(0, n - width(s))


def bar(v, n=30):
    k = int(round(v * n))
    return "#" * k + "." * (n - k)


# ---------------------------------------------------------------- 1. 置信区间

def wilson(k, n, z=1.96):
    """Wilson 得分区间。比 Wald 区间好在 p 接近 0/1 或 n 小时不会越界。"""
    p = k / float(n)
    d = 1.0 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4.0 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def section_ci():
    print("=" * 76)
    print("1. 置信区间：n 次试验的成功率，误差棒有多长")
    print("=" * 76)
    print("假设真实成功率 75%，用不同试验次数去测，得到 95% Wilson 区间：\n")
    print(pad("n", 8) + pad("观测成功数", 12) + pad("点估计", 10)
          + pad("95% 区间", 22) + pad("区间宽度", 12) + "误差棒")
    print("-" * 76)
    for n, k in ((10, 8), (20, 15), (50, 38), (100, 75), (200, 150),
                 (400, 300), (1000, 750)):
        lo, hi = wilson(k, n)
        print(pad(str(n), 8) + pad(str(k), 12) + pad("%.1f%%" % (k / n * 100), 10)
              + pad("[%.1f%%, %.1f%%]" % (lo * 100, hi * 100), 22)
              + pad("%.1f pt" % ((hi - lo) * 100), 12)
              + bar((hi - lo)))

    print("\n读法：n=20 时区间宽度 36 个百分点 —— 「75%」这个数字的真实含义是")
    print("「在 53% 到 89% 之间，我不知道」。而论文里这个数字通常写成「75%」。")
    print("想要 ±5 个百分点（区间宽度 10 pt），需要约 300 次试验。")

    print("\n另一个更狠的说法：两次实验都报 70%，但一次 7/10、一次 70/100 ——")
    for k, n in ((7, 10), (70, 100)):
        lo, hi = wilson(k, n)
        print(f"  {k}/{n}: [{lo*100:.1f}%, {hi*100:.1f}%]")
    print("  两个区间几乎完全重叠。7/10 这个结果，什么也说明不了。")


# ---------------------------------------------------------------- 2. 功效

def sample_size(p1, p2, alpha=0.05, power=0.80):
    """两比例检验，每组所需样本量（正态近似）。"""
    z_a = 1.959964 if alpha == 0.05 else 1.644854
    z_b = 0.841621 if power == 0.80 else 1.281552
    pbar = (p1 + p2) / 2.0
    num = (z_a * math.sqrt(2 * pbar * (1 - pbar))
           + z_b * math.sqrt(p1 * (1 - p1) + p2 * (1 - p2))) ** 2
    return num / ((p1 - p2) ** 2)


def section_power():
    print("\n" + "=" * 76)
    print("2. 要多少次试验才能分出高下（两比例检验，80% 功效，α=0.05）")
    print("=" * 76)
    print("假设新方法 80%，基线 60~79%。每组需要：\n")
    print(pad("基线", 10) + pad("提升", 10) + pad("每组 n", 12) + pad("总 rollout", 14)
          + pad("单臂耗时", 12) + "现实含义")
    print("-" * 76)
    SEC_PER_TRIAL = 180.0     # 60 s 执行 + 120 s 复位/物体摆放
    for p2 in (0.60, 0.65, 0.70, 0.75, 0.78):
        n = int(math.ceil(sample_size(p2, 0.80)))
        total = 2 * n
        hours = total * SEC_PER_TRIAL / 3600.0
        days = hours / 8.0
        note = ("%.0f 小时（%.1f 个工作日）" % (hours, days)) if hours > 0 else "-"
        print(pad("%.0f%%" % (p2 * 100), 10) + pad("+%.0f pt" % ((0.80 - p2) * 100), 10)
              + pad(str(n), 12) + pad(str(total), 14)
              + pad("%.0f h" % hours, 12) + note)

    print("\n单次 rollout 按 180 s 估（60 s 执行 + 120 s 复位与摆放物体，")
    print("单人单臂，不含失败后的排查）。这是乐观值。")
    print("\n结论：想证明「提升 5 个百分点」，需要 ~2200 次 rollout ≈ 110 小时")
    print("纯机器时间。这就是为什么真实论文里 5 pt 的差距基本没法验证 ——")
    print("它不是不重要，是**测不出来**。")

    print("\n如果只能在有限预算里做，唯一可行的方向是**降低单次试验的方差**：")
    print("固定初始条件、减少人工复位、用自动化重置工装。这属于数据平台的活。")


# ---------------------------------------------------------------- 3. 测试分布

def section_distribution():
    print("\n" + "=" * 76)
    print("3. 成功率是对测试分布求平均 —— 换分布，差距能差十倍")
    print("=" * 76)

    # 这两条曲线来自实验 1（05_learning_from_data/01_bc_and_dagger.py）
    offsets = (0.00, 0.05, 0.10, 0.15, 0.20, 0.25, 0.30)
    bc = (1.000, 0.940, 0.695, 0.410, 0.305, 0.275, 0.190)
    dagger = (1.000, 0.935, 0.790, 0.630, 0.735, 0.880, 0.840)

    print("两条真实曲线（实验 1 的结果，起点偏移 → 成功率）：\n")
    print(pad("起点偏移", 12) + pad("BC(120条)", 14) + pad("DAgger(5轮)", 14) + "差距")
    print("-" * 76)
    for i, r in enumerate(offsets):
        print(pad("%.2f m" % r, 12) + pad("%.1f%%" % (bc[i] * 100), 14)
              + pad("%.1f%%" % (dagger[i] * 100), 14)
              + "%+.1f pt" % ((dagger[i] - bc[i]) * 100))

    print("\n现在把它们放到三种测试分布下平均。注意圆盘上均匀采样时，")
    print("半径 r 处的样本密度正比于 r（面积元 2πr dr）—— 外圈权重更大。\n")
    print(pad("测试分布", 22) + pad("BC 平均", 12) + pad("DAgger 平均", 12)
          + pad("差值", 10) + "谁赢")
    print("-" * 76)
    for label, R in (("半径 0.10 m 的圆盘", 0.10), ("半径 0.20 m 的圆盘", 0.20),
                     ("半径 0.30 m 的圆盘", 0.30)):
        # 对每个半径点用「该环带内的面积权重」近似：r 落在 [r_i-d, r_i+d]
        w = [max(0.0, min(R, r + 0.025) ** 2 - max(0.0, r - 0.025) ** 2)
             for r in offsets]
        tot = sum(w)
        if tot <= 0:
            continue
        b = sum(wi * bi for wi, bi in zip(w, bc)) / tot
        d = sum(wi * di for wi, di in zip(w, dagger)) / tot
        win = "DAgger" if d > b else "BC"
        print(pad(label, 22) + pad("%.1f%%" % (b * 100), 12)
              + pad("%.1f%%" % (d * 100), 12) + pad("%+.1f pt" % ((d - b) * 100), 10)
              + win)

    print("\n同一批模型、同一份数据，唯一变的是**测试集从哪里采样**：")
    print("  · 窄分布（半径 0.10）：差 4 pt ——「几乎一样好」")
    print("  · 宽分布（半径 0.30）：差 41 pt ——「完全不是一个量级」")
    print("4 pt 和 41 pt 差了一个数量级。更麻烦的是：回到第 1 节，n=100 时")
    print("置信区间宽度就有 17 pt —— 那个 4 pt 的差距本来也测不出来。")
    print("\n所以「成功率 78%」这句话，不写清楚测试分布，等于什么都没说。")
    print("一个可用的报告格式至少要包含：扰动类型、幅度分布、试验次数、置信区间。")


# ---------------------------------------------------------------- 4. 泄漏

def section_leakage():
    print("\n" + "=" * 76)
    print("4. 评测集泄漏：训练场景和评测场景有多像")
    print("=" * 76)

    print("设：在没见过的场景上成功率 60%，在见过的场景上 95%。")
    print("如果评测集里混进了训练场景（或同一个场景的不同初始位置），")
    print("报告出来的数字是两者的加权平均：\n")
    print(pad("重叠比例", 14) + pad("报告成功率", 14) + pad("虚高", 10) + "说明")
    print("-" * 76)
    for f in (0.0, 0.05, 0.10, 0.20, 0.30, 0.50):
        rep = f * 0.95 + (1 - f) * 0.60
        note = "无泄漏" if f == 0 else ("看不出来" if f <= 0.05 else
                                        "已经能改变结论" if f <= 0.2 else "基本是背答案")
        print(pad("%.0f%%" % (f * 100), 14) + pad("%.1f%%" % (rep * 100), 14)
              + pad("+%.1f pt" % ((rep - 0.60) * 100), 10) + note)

    print("\n20% 的重叠 → 报告 67% 而真实泛化 60%，虚高 7 pt。")
    print("这个量级刚好和「值得发论文的提升」重合 —— 也是最难发现的一类错误。")

    print("\n三类常被忽略的泄漏：")
    print("  1. 同场景不同初始位置：看起来是「新 episode」，其实是同一个背景、")
    print("     同一批物体、同一种光照。模型学到的是背景，不是任务。")
    print("  2. 同物体不同摆放：材质、颜色、尺寸都没变，泛化能力没被测到。")
    print("  3. 调参用的验证集和最终测试集同源：超参是在测试分布上选的。")

    print("\n检测方法只有一个：**按场景 ID 而不是按 episode ID 划分**。")
    print("并且要把场景的元数据（背景、物体集合、光照、相机位置）存进数据集 ——")
    print("没有这些字段，你连「有没有泄漏」都判断不了。")


# ---------------------------------------------------------------- 主流程

def main():
    section_ci()
    section_power()
    section_distribution()
    section_leakage()

    print("\n" + "=" * 76)
    print("小结：一个诚实的评测协议至少要写清什么")
    print("=" * 76)
    items = [
        ("测试分布", "初始条件怎么采、扰动幅度多大、是不是圆盘均匀"),
        ("试验次数", "每组 n，以及为什么是这个 n（功效分析）"),
        ("置信区间", "点估计 + 95% 区间，不要只给点估计"),
        ("场景划分", "按场景 ID 而非 episode ID；重叠比例写出来"),
        ("失败定义", "超时算失败吗？撞了算失败吗？人工中断算吗"),
        ("评估频率", "chunk 长度、控制频率 —— 否则反应延迟不可比"),
        ("重置方式", "人工复位还是自动；人工复位会引入操作者偏差"),
    ]
    for a, b in items:
        print("  · " + pad(a, 12) + b)

    print("\n缺任何一项，数字都不可复现。而「不可复现」在机器人领域不是")
    print("学术问题，是工程问题：你没法判断新版本到底有没有变好。")
    print("\n对数据平台的含义：评测集本身也是一个数据集，需要版本、需要")
    print("场景元数据、需要防泄漏的划分规则。它和训练集一样要管。")


if __name__ == "__main__":
    main()
